/** 简历上下文消息的包装模板（用户注入简历时使用） */
export const RESUME_CONTEXT_TEMPLATE = (resumeTexts: string[]): string => {
  if (resumeTexts.length === 1) {
    return `以下是用户的简历内容，请基于此回答后续提问：\n\n${resumeTexts[0]}`
  }
  return resumeTexts
    .map((text, i) => `=== 简历 ${i + 1} ===\n${text}`)
    .join('\n\n')
    .replace(/^/, '以下是用户的多份简历内容，请基于这些回答后续提问：\n\n')
}

